def energy():
    e=0.0
    for i in range(5):
        b=B[i]; e+=0.5*b[6]*(b[3]*b[3]+b[4]*b[4]+b[5]*b[5])
        for j in range(i+1,5):
            c=B[j]; dx=b[0]-c[0]; dy=b[1]-c[1]; dz=b[2]-c[2]; e-=b[6]*c[6]/math.sqrt(dx*dx+dy*dy+dz*dz)
    return e
